"""
Qdrant Vector Store Service

Manages vector storage and retrieval using Qdrant for the knowledge base system.
Uses local file storage mode. Embeddings are generated by the unified
services.embedding_service (OpenAI-compatible, with deterministic fallback).
"""

from __future__ import annotations

import hashlib
import logging
from pathlib import Path
from typing import Any

from qdrant_client import QdrantClient
from qdrant_client.models import (
    Distance,
    FieldCondition,
    Filter,
    MatchAny,
    PointStruct,
    VectorParams,
)

from services.embedding_service import get_embedding_service

logger = logging.getLogger(__name__)


def stable_point_id(point_id: str) -> int:
    """
    Generate a deterministic, positive 63-bit integer ID from a string.

    Python's built-in hash() is randomized per process (PYTHONHASHSEED), so
    point IDs derived from it change on every restart, making upsert/dedup
    impossible. sha256-based IDs are stable across processes and machines.
    """
    digest = hashlib.sha256(point_id.encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "big") & 0x7FFFFFFFFFFFFFFF


def extract_chunk_text(chunk: dict[str, Any]) -> str:
    """
    Extract text from a chunk dict.

    Tolerates both the parser/normalized schema ('text') and the rag_pipeline
    schema ('content').
    """
    text = chunk.get("text")
    if isinstance(text, str) and text:
        return text
    content = chunk.get("content")
    if isinstance(content, str):
        return content
    return ""


def resolve_chunk_index(chunk: dict[str, Any], position: int) -> int:
    """
    Resolve chunk_index from a chunk dict; falls back to 1-based position.

    Looks at top-level 'chunk_index' first, then 'metadata.chunk_index'.
    """
    candidate = chunk.get("chunk_index")
    if isinstance(candidate, bool) or not isinstance(candidate, int):
        metadata = chunk.get("metadata")
        candidate = metadata.get("chunk_index") if isinstance(metadata, dict) else None
    if isinstance(candidate, bool) or not isinstance(candidate, int) or candidate < 1:
        return position + 1
    return candidate


class QdrantVectorStore:
    """
    Qdrant-based vector store for knowledge base chunks.

    Schema:
    - doc_id: Document identifier
    - chunk_index: Index of chunk within document
    - text: Raw text content
    - kb_id: Knowledge base identifier
    - folder_id: Folder identifier (optional)
    """

    def __init__(
        self,
        collection_name: str = "knowledge_base",
        vector_size: int | None = None,
        storage_path: str = "./data/qdrant",
    ):
        """
        Initialize Qdrant vector store with local file storage.

        Args:
            collection_name: Name of the Qdrant collection
            vector_size: Dimension of embedding vectors; defaults to
                EMBEDDING_DIM from the unified embedding service
            storage_path: Path for local file storage
        """
        self.collection_name = collection_name
        self.vector_size = vector_size or get_embedding_service().dim
        self.storage_path = Path(storage_path)

        # Ensure storage directory exists
        self.storage_path.mkdir(parents=True, exist_ok=True)

        # Initialize Qdrant client with local file storage
        self.client = QdrantClient(path=str(self.storage_path))

        # Create collection if it doesn't exist
        self._ensure_collection()

    def _ensure_collection(self) -> None:
        """Create collection if missing; rebuild when vector size mismatches."""
        collections = self.client.get_collections().collections
        collection_names = [col.name for col in collections]

        if self.collection_name in collection_names:
            # 维度一致性检查：与 EMBEDDING_DIM 不符时删除重建（开发阶段数据可丢弃）
            info = self.client.get_collection(collection_name=self.collection_name)
            vectors_cfg = info.config.params.vectors
            existing_size = getattr(vectors_cfg, "size", None)
            if existing_size is not None and existing_size != self.vector_size:
                logger.warning(
                    "[QdrantVectorStore] collection '%s' 维度不一致(已有=%s, 期望=%d)，"
                    "删除重建（开发阶段数据可丢弃）",
                    self.collection_name, existing_size, self.vector_size,
                )
                self.client.delete_collection(collection_name=self.collection_name)
            else:
                return

        self.client.create_collection(
            collection_name=self.collection_name,
            vectors_config=VectorParams(
                size=self.vector_size,
                distance=Distance.COSINE,
            ),
        )

    def upsert_vectors(
        self,
        doc_id: str,
        chunks: list[dict[str, Any]],
        embeddings: list[list[float]] | None = None,
        kb_id: str | None = None,
        folder_id: str | None = None,
    ) -> dict[str, Any]:
        """
        Insert or update vectors for a document's chunks.

        Args:
            doc_id: Document identifier. Pipeline writes use the unified
                "doc-{id}" naming so delete_vectors() can cascade cleanly.
            chunks: List of chunk dictionaries. Text is read from 'text' or
                'content' (rag_pipeline schema); chunk_index is resolved from
                top-level 'chunk_index', then 'metadata.chunk_index', then
                the 1-based position in the list.
            embeddings: Pre-computed embeddings. If None, generated via the
                unified embedding service (degrades to deterministic fake
                vectors when EMBEDDING_API_KEY is not configured).
            kb_id: Knowledge base identifier
            folder_id: Folder identifier (optional)

        Returns:
            Dictionary with operation status and count
        """
        if not chunks:
            return {"success": True, "count": 0, "doc_id": doc_id}

        # Generate embeddings if not provided（统一走 embedding_service）
        if embeddings is None:
            embeddings = get_embedding_service().embed_texts(
                [extract_chunk_text(chunk) for chunk in chunks]
            )

        if len(embeddings) != len(chunks):
            raise ValueError(f"Embedding count ({len(embeddings)}) must match chunk count ({len(chunks)})")

        # Prepare points for upsert
        points: list[PointStruct] = []
        for idx, (chunk, embedding) in enumerate(zip(chunks, embeddings)):
            chunk_index = resolve_chunk_index(chunk, idx)
            point_id = f"{doc_id}_{chunk_index}"

            payload = {
                "doc_id": doc_id,
                "chunk_index": chunk_index,
                "text": extract_chunk_text(chunk),
                "kb_id": kb_id or "",
                "folder_id": folder_id or "",
            }

            points.append(
                PointStruct(
                    id=stable_point_id(point_id),  # Deterministic positive integer ID
                    vector=embedding,
                    payload=payload,
                )
            )

        # Upsert to Qdrant
        self.client.upsert(
            collection_name=self.collection_name,
            points=points,
        )

        return {
            "success": True,
            "count": len(points),
            "doc_id": doc_id,
        }

    def search_vectors(
        self,
        query_vector: list[float],
        limit: int = 10,
        kb_ids: list[str] | None = None,
        folder_ids: list[str] | None = None,
    ) -> list[dict[str, Any]]:
        """
        Search for similar vectors in the collection.

        Args:
            query_vector: Query embedding vector
            limit: Maximum number of results to return
            kb_ids: List of knowledge base IDs to filter by (optional)
            folder_ids: List of folder IDs to filter by (optional)

        Returns:
            List of search results with payload and score
        """
        # Build filter conditions
        must_conditions = []

        if kb_ids:
            must_conditions.append(
                FieldCondition(
                    key="kb_id",
                    match=MatchAny(any=kb_ids),
                )
            )

        if folder_ids:
            must_conditions.append(
                FieldCondition(
                    key="folder_id",
                    match=MatchAny(any=folder_ids),
                )
            )

        # Create filter if conditions exist
        search_filter = Filter(must=must_conditions) if must_conditions else None

        # Search in Qdrant using query_points (newer API)
        try:
            search_results = self.client.query_points(
                collection_name=self.collection_name,
                query=query_vector,
                limit=limit,
                query_filter=search_filter,
            ).points
        except AttributeError:
            # Fallback to older search API
            search_results = self.client.search(
                collection_name=self.collection_name,
                query_vector=query_vector,
                limit=limit,
                query_filter=search_filter,
            )

        # Format results
        results = []
        for hit in search_results:
            results.append({
                "id": hit.id,
                "score": hit.score,
                "doc_id": hit.payload.get("doc_id"),
                "chunk_index": hit.payload.get("chunk_index"),
                "text": hit.payload.get("text"),
                "kb_id": hit.payload.get("kb_id"),
                "folder_id": hit.payload.get("folder_id"),
            })

        return results

    def delete_vectors(self, doc_id: str) -> dict[str, Any]:
        """
        Delete all vectors associated with a document.

        Args:
            doc_id: Document identifier

        Returns:
            Dictionary with operation status
        """
        # Delete points by filtering on doc_id
        self.client.delete(
            collection_name=self.collection_name,
            points_selector=Filter(
                must=[
                    FieldCondition(
                        key="doc_id",
                        match=MatchAny(any=[doc_id]),
                    )
                ]
            ),
        )

        return {
            "success": True,
            "doc_id": doc_id,
        }

    def get_collection_info(self) -> dict[str, Any]:
        """
        Get information about the collection.

        Returns:
            Dictionary with collection metadata
        """
        info = self.client.get_collection(collection_name=self.collection_name)
        return {
            "name": self.collection_name,
            "vector_size": self.vector_size,
            "points_count": info.points_count,
            "status": info.status,
        }
